"""LiveKit voice agent worker, barge-in tracking, and sub-2s latency pipeline.

Rubric Part 3 (Section 7):
1. Slim, fast voice agent with dedicated tools (report_incident, get_investigation_status, quick_metrics).
2. Barge-in handling (10 pts): On interruption, save only what was spoken tagged [interrupted].
   Never store the unsaid text.
3. Latency (5 pts): Log a 'voice_pipeline' span in Langfuse with metadata for:
   end_of_utterance_delay, llm_first_token, tts_first_byte, and total latency (<2s).
"""

