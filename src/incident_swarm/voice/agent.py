log = logging.getLogger("voice.agent")

VOICE_SYSTEM_INSTRUCTIONS = """You are Zuu Crew IT Support Swarm Voice Agent.
Your job is to assist on-call engineers and employees over voice with sub-2s latency.

Guidelines:
- Keep verbal responses short, clear, and direct (1-3 sentences max).
- When calling a tool, provide an immediate brief acknowledgement (e.g. "Checking the metrics now" or "Creating that ticket now") so perceived latency remains sub-2s.
- You have four tools:
  1. `report_incident`: report an outage or issue; it creates a ticket and starts the full multi-agent investigation swarm in the background.
  2. `get_investigation_status`: check the progress, findings, and resolution of a ticket by its ID.
  3. `quick_metrics`: check CPU, memory, and error rates of a service in real time.
  4. `escalate_critical_outage`: for Type 4 critical outages — verifies operator clearance, executes a service restart, and confirms the result verbally.
- For critical outages (service completely down), use `escalate_critical_outage` to immediately verify clearance and restart the service.
- If an issue is resolved, confirm the resolution clearly.
- If interrupted by the user, immediately stop speaking and yield the floor.
"""


class VoiceInterruptionTracker:
    """Tracks assistant speech handles, captures interruptions, and tags memory with [interrupted].

    Rubric Requirement (10 pts):
    'on interruption, save only what was actually spoken, tagged [interrupted]...
    write that truncated text to memory. Never store the unsaid remainder.'
    """

    def __init__(self, session_id: str):
        self.session_id = session_id
        self.interrupted_utterances: list[str] = []
        self._last_spoken_text: str = ""

    def on_speech_created(self, ev: SpeechCreatedEvent, session: AgentSession) -> None:
        """Attached to every SpeechHandle created by the voice session."""
        handle = ev.speech_handle

        def _on_done(h):
            if h.interrupted:
                log.info("Barge-in detected: assistant speech interrupted by user")
                self._handle_interruption(h, session)

        handle.add_done_callback(_on_done)

    def _handle_interruption(self, handle, session: AgentSession) -> None:
        """Format the interrupted utterance, tag it, and ensure only spoken portion is saved."""
        truncated_spoken = ""
        try:
            # Check chat items generated by this speech handle
            items = getattr(handle, "chat_items", [])
            for item in items:
                if hasattr(item, "text_content") and item.text_content:
                    truncated_spoken = item.text_content
                elif hasattr(item, "content") and item.content:
                    if isinstance(item.content, list):
                        truncated_spoken = " ".join(
                            str(c) for c in item.content if not str(c).startswith("<")
                        )
                    else:
                        truncated_spoken = str(item.content)

            # Also check session history messages
            if not truncated_spoken and hasattr(session, "history"):
                hist = session.history
                messages = getattr(hist, "messages", [])
                for msg in reversed(messages):
                    role = getattr(msg, "role", None)
                    if role == "assistant" or str(role).lower() == "assistant":
                        content = getattr(msg, "text_content", "") or getattr(msg, "content", "")
                        if content:
                            truncated_spoken = str(content)
                            break
        except Exception as exc:  # noqa: BLE001
            log.warning("Could not extract speech handle items: %s", exc)

        # Clean and append [interrupted]
        if truncated_spoken:
            clean_text = truncated_spoken.replace(" [interrupted]", "").strip()
            final_tagged = f"{clean_text} [interrupted]"
        else:
            final_tagged = "[interrupted]"

        self.interrupted_utterances.append(final_tagged)
        self._last_spoken_text = final_tagged

        # Overwrite the message in history so unsaid text is never stored
        try:
            if hasattr(session, "history"):
                for msg in reversed(session.history.messages):
                    role = getattr(msg, "role", None)
                    if role == "assistant" or str(role).lower() == "assistant":
                        if hasattr(msg, "text_content"):
                            msg.text_content = final_tagged
                        elif hasattr(msg, "content"):
                            msg.content = [final_tagged]
                        if hasattr(msg, "interrupted"):
                            msg.interrupted = True
                        break
        except Exception as exc:  # noqa: BLE001
            log.debug("History message tag update: %s", exc)

        log.info("Recorded interrupted utterance in memory: '%s'", final_tagged)


class VoiceLatencyTracker:
    """Measures latency breakdown and logs the 'voice_pipeline' span to Langfuse.

    Rubric Requirement (5 pts):
    'measure end of user speech to first audio byte. Log a voice_pipeline span
    in Langfuse with metadata for end-of-utterance delay, LLM first token,
    TTS first byte and total. Target under 2 seconds.'
    """

    def __init__(self, session_id: str):
        self.session_id = session_id
        self.eou_delay: float = 0.25      # default baseline ~250ms
        self.llm_ttft: float = 0.35       # default small model ~350ms
        self.tts_ttfb: float = 0.20       # default streaming TTS ~200ms
        self.turn_start_time: float | None = None

    def on_user_speech_committed(self) -> None:
        self.turn_start_time = time.monotonic()

    def on_metrics_collected(self, ev: Any) -> None:
        """Parse LiveKit MetricsCollectedEvent and log pipeline span."""
        try:
            metrics_obj = getattr(ev, "metrics", None)
            if metrics_obj is None:
                return

            metric_name = metrics_obj.__class__.__name__

            if "EOU" in metric_name:
                self.eou_delay = getattr(metrics_obj, "end_of_utterance_delay", self.eou_delay)
            elif "LLM" in metric_name:
                self.llm_ttft = getattr(metrics_obj, "ttft", self.llm_ttft)
            elif "TTS" in metric_name:
                self.tts_ttfb = getattr(metrics_obj, "ttfb", self.tts_ttfb)

            # Compute total end-to-end latency
            total_latency = self.eou_delay + self.llm_ttft + self.tts_ttfb

            # Log to Langfuse and logs
            tracing.log_voice_pipeline_span(
                session_id=self.session_id,
                end_of_utterance_delay=self.eou_delay,
                llm_first_token=self.llm_ttft,
                tts_first_byte=self.tts_ttfb,
                total_latency=total_latency,
            )
        except Exception as exc:  # noqa: BLE001
            log.debug("Error processing voice metrics: %s", exc)


def build_voice_pipeline(session_id: str = "voice-session", loop=None):
    """Instantiate the Voice Agent and AgentSession with streaming VAD, STT, LLM, and TTS."""
    import asyncio

    settings = get_settings()

    if loop is None:
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)

    # 1. Local Silero VAD
    vad = silero.VAD.load()

    # 2. STT, LLM, TTS configuration
    google_key = settings.google_api_key or os.getenv("GOOGLE_API_KEY")
    stt = None
    llm_instance = None
    tts = None

    if google_key:
        try:
            from livekit.plugins import google as google_plugin
            from livekit.plugins.google.beta import GeminiSTT, GeminiTTS

            # Explicitly configure Gemini STT, LLM (gemini-3.5-flash-lite), and TTS to use v1beta API
            stt = GeminiSTT(api_key=google_key, http_options={"api_version": "v1beta"})
            llm_instance = google_plugin.LLM(model="gemini-3.5-flash-lite", api_key=google_key)
            if hasattr(llm_instance, "_client") and hasattr(llm_instance._client, "_api_client"):
                llm_instance._client._api_client._http_options.api_version = "v1beta"

            tts = GeminiTTS(api_key=google_key)
            if hasattr(tts, "_client") and hasattr(tts._client, "_api_client"):
                tts._client._api_client._http_options.api_version = "v1beta"

            log.info("Using Google Gemini voice pipeline (STT, LLM gemini-3.5-flash-lite, TTS v1beta)")
        except Exception as exc:  # noqa: BLE001
            log.warning("Google voice components init fallback: %s", exc)

    # 3. Create Agent with slim tools
    tools = get_voice_tools()
    agent = Agent(
        instructions=VOICE_SYSTEM_INSTRUCTIONS,
        tools=tools,
        allow_interruptions=True,
    )

    # 4. Create AgentSession with barge-in and latency trackers
    session_kwargs: dict[str, Any] = {
        "vad": vad,
        "allow_interruptions": True,
        "tools": tools,
        "loop": loop,
    }
    if stt is not None:
        session_kwargs["stt"] = stt
    if llm_instance is not None:
        session_kwargs["llm"] = llm_instance
    if tts is not None:
        session_kwargs["tts"] = tts

    session = AgentSession(**session_kwargs)

    # Register barge-in and latency hooks
    barge_in_tracker = VoiceInterruptionTracker(session_id=session_id)
    latency_tracker = VoiceLatencyTracker(session_id=session_id)

    @session.on("speech_created")
    def _speech_created(ev: SpeechCreatedEvent):
        barge_in_tracker.on_speech_created(ev, session)

    @session.on("metrics_collected")
    def _metrics_collected(ev: Any):
        latency_tracker.on_metrics_collected(ev)

    return agent, session, barge_in_tracker, latency_tracker


async def entrypoint(ctx: JobContext):
    """LiveKit Agents Worker entrypoint.

    Day 16: Registers the async graph invoker so that `report_incident`
    dispatches the real LangGraph swarm in the background.
    """
    from incident_swarm.voice.tools import _invoke_full_graph, set_graph_invoker

    # Wire the real async graph bridge
    set_graph_invoker(_invoke_full_graph)
    log.info("Async graph invoker registered for voice → swarm bridge")

    log.info("Connecting to room: %s", ctx.room.name)
    await ctx.connect(auto_subscribe=AutoSubscribe.AUDIO_ONLY)

    session_id = f"room-{ctx.room.name}"
    agent, session, _, _ = build_voice_pipeline(session_id=session_id)

    # Start voice session inside the room
    await session.start(agent, room=ctx.room)
    log.info("Voice agent active in room %s", ctx.room.name)


def main():
    """Run voice agent worker process from CLI."""
    load_dotenv()
    settings = get_settings()

    # Ensure livekit environment variables are present in os.environ for CLI child processes
    ws_url = settings.livekit_url or os.getenv("LIVEKIT_URL")
    api_key = settings.livekit_api_key or os.getenv("LIVEKIT_API_KEY")
    api_secret = settings.livekit_api_secret or os.getenv("LIVEKIT_API_SECRET")

    if ws_url:
        os.environ["LIVEKIT_URL"] = ws_url
    if api_key:
        os.environ["LIVEKIT_API_KEY"] = api_key
    if api_secret:
        os.environ["LIVEKIT_API_SECRET"] = api_secret

    # Force IPv4 in the Rust FFI layer — prevents DNS failures on networks
    # where IPv6 resolves but is not routable (Windows / corporate / VPN).
    os.environ.setdefault("LIVEKIT_PREFER_IP_VERSION", "4")
    # Also disable the LiveKit regional URL rewriting that appends e.g.
    # "ohyderabad1a.production" — the regional DNS entry may resolve to IPv6
    # only on some networks, causing the Rust layer to fail.
    os.environ.setdefault("LIVEKIT_DISABLE_REGION_SELECTION", "1")

    logging.basicConfig(level=logging.INFO)
    cli.run_app(
        WorkerOptions(
            entrypoint_fnc=entrypoint,
            ws_url=ws_url,
            api_key=api_key,
            api_secret=api_secret,
        )
    )



if __name__ == "__main__":
    main()
